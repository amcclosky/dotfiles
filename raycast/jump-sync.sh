#!/bin/bash

# Required parameters:
# @raycast.schemaVersion 1
# @raycast.title Jump Desktop: Sync Computers
# @raycast.mode silent
# @raycast.packageName Jump Desktop
# @raycast.icon 🔄

# Generates one Raycast script command per saved computer in Jump Desktop, so each
# shows up in Raycast search as "Jump: <name>". Re-run after adding/renaming/removing
# a computer in Jump.

servers_dir="${JUMP_SERVERS_DIR:-$HOME/Documents/JumpDesktop/Viewer/Servers}"
out_dir="$(cd "$(dirname "$0")" && pwd)"

tag="@ray""cast"

mkdir -p "$out_dir"
rm -f "$out_dir"/jump-computer-*.sh

count=0
for f in "$servers_dir"/*.jump; do
  [ -e "$f" ] || continue

  name=$(plutil -extract DisplayName raw -o - "$f" 2>/dev/null | tr -d '\r\n')
  [ -n "$name" ] || continue
  # Computer files end in "<UUID>.jump"; the UUID is stable across renames.
  uuid=$(basename "$f" .jump | grep -oE '[0-9A-Fa-f]{8}(-[0-9A-Fa-f]{4}){3}-[0-9A-Fa-f]{12}$')
  [ -n "$uuid" ] || continue

  slug=$(printf '%s' "$name" | tr -c 'A-Za-z0-9._-' '-')
  script="$out_dir/jump-computer-$slug-${uuid:0:8}.sh"

  # Metadata prefix is built at runtime so the literal tag only appears once in this file.
  cat >"$script" <<EOF
#!/bin/bash

# Generated by jump-sync.sh. Do not edit.
# ${tag}.schemaVersion 1
# ${tag}.title Jump: $name
# ${tag}.mode silent
# ${tag}.packageName Jump Desktop
# ${tag}.icon 🖥️

f=\$(ls "$servers_dir"/*$uuid.jump 2>/dev/null | head -1)
if [ -z "\$f" ]; then
  echo "Computer no longer exists. Run Jump Desktop: Sync Computers"
  exit 1
fi

if [ -n "\$JUMP_DRY_RUN" ]; then
  echo "\$f"
  exit 0
fi

open "\$f"
echo "Opening Jump session"
EOF
  chmod +x "$script"

  # Disconnect command: delegates to jump-disconnect.sh with an exact window-title match.
  dscript="$out_dir/jump-computer-disconnect-$slug-${uuid:0:8}.sh"
  cat >"$dscript" <<EOF
#!/bin/bash

# Generated by jump-sync.sh. Do not edit.
# ${tag}.schemaVersion 1
# ${tag}.title Jump: Disconnect $name
# ${tag}.mode silent
# ${tag}.packageName Jump Desktop
# ${tag}.icon ❌

JUMP_EXACT=1 exec "\$(dirname "\$0")/jump-disconnect.sh" $(printf '%q' "$name")
EOF
  chmod +x "$dscript"
  count=$((count + 1))
done

echo "Synced $count Jump computer(s)"
